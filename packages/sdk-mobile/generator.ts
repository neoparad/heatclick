export function generateMobileSdkForPlatform(platform: MobilePlatform): GeneratedMobileSdkArtifact {
  const schemaVersion = CANONICAL_SCHEMA.meta.schemaVersion;
  let files: ReadonlyArray<MobileGeneratedFile>;
  let language: GeneratedMobileSdkArtifact['language'];

  switch (platform) {
    case 'ios':
      language = 'swift';
      files = generateIosSwiftSdk(schemaVersion);
      break;
    case 'android':
      language = 'kotlin';
      files = generateAndroidKotlinSdk(schemaVersion);
      break;
    case 'react_native':
      language = 'typescript';
      files = generateReactNativeTsSdk(schemaVersion);
      break;
    case 'flutter':
      language = 'dart';
      files = generateFlutterDartSdk(schemaVersion);
      break;
  }

  const manifestSha256 = sha256Hex(
    canonicalJson({
      platform,
      language,
      contractSchemaVersion: schemaVersion,
      files: files.map((f) => ({ path: f.path, sha256: f.sha256 })),
    })
  );

  return {
    platform,
    language,
    contractSchemaVersion: schemaVersion,
    files,
    manifestSha256,
  };
}

export function generateAll4MobileSdks(): {
  readonly artifacts: Readonly<Record<MobilePlatform, GeneratedMobileSdkArtifact>>;
  readonly combinedManifestSha256: string;
} {
  const artifacts = {} as Record<MobilePlatform, GeneratedMobileSdkArtifact>;
  const manifests: Record<string, string> = {};
  for (const p of MOBILE_PLATFORMS) {
    const art = generateMobileSdkForPlatform(p);
    artifacts[p] = art;
    manifests[p] = art.manifestSha256;
  }
  return {
    artifacts,
    combinedManifestSha256: sha256Hex(canonicalJson(manifests)),
  };
}
