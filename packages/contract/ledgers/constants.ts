const CONSTANT_MAP = new Map<string, ConstantEntry>(
  CONSTANTS_LEDGER.map((entry) => [entry.id, entry]),
)

export function getConstant(id: string): ConstantEntry | undefined {
  return CONSTANT_MAP.get(id)
}

export function getConstantsByDomain(domain: ConstantDomain): ReadonlyArray<ConstantEntry> {
  return CONSTANTS_LEDGER.filter((entry) => entry.domain === domain)
}

/**
 * Validate whether a proposed numeric override respects the constant's declared `mutableRange`.
 */
export function isWithinMutableRange(id: string, proposedValue: number): boolean {
  const entry = CONSTANT_MAP.get(id)
  if (!entry || typeof entry.value !== 'number' || !Number.isFinite(proposedValue)) {
    return false
  }
  if (entry.mutableRange.immutable) {
    return proposedValue === entry.value
  }
  if (entry.mutableRange.min !== undefined && proposedValue < entry.mutableRange.min) {
    return false
  }
  if (entry.mutableRange.max !== undefined && proposedValue > entry.mutableRange.max) {
    return false
  }
  return true
}
