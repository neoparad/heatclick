/**
 * Look up a gate by canonical id (e.g. `tel.G16`, `surf.G1`) or working-doc alias (`sur.G1`).
 */
export function getGate(gateId: string): GateEntry | undefined {
  return GATE_BY_ID.get(gateId) ?? GATE_BY_ALIAS.get(gateId)
}

export function getGatesByDomain(domain: GateDomain): ReadonlyArray<GateEntry> {
  return GATES_LEDGER.filter((entry) => entry.domain === domain)
}

export function getGatesByStep(step: string): ReadonlyArray<GateEntry> {
  return GATES_LEDGER.filter((entry) => entry.step === step)
}

/**
 * Compute `GET /v1/sites/{id}/capabilities` equivalent summary directly from the gate & decision ledgers.
 */
export function getCapabilitiesSummary(options: CapabilitiesSummaryOptions = {}): CapabilitiesSummary {
  const sourceGates = options.domain
    ? GATES_LEDGER.filter((entry) => entry.domain === options.domain)
    : GATES_LEDGER

  const byDomain: Record<GateDomain, { total: number; open: number; closed: number }> = {
    tel: { total: 0, open: 0, closed: 0 },
    store: { total: 0, open: 0, closed: 0 },
    join: { total: 0, open: 0, closed: 0 },
    act: { total: 0, open: 0, closed: 0 },
    ml: { total: 0, open: 0, closed: 0 },
    ev: { total: 0, open: 0, closed: 0 },
    del: { total: 0, open: 0, closed: 0 },
    surf: { total: 0, open: 0, closed: 0 },
  }

  let openCount = 0
  let closedCount = 0
  let blockedByDecisionCount = 0

  const capabilities: CapabilityItem[] = sourceGates.map((entry) => {
    const unmetDecisions: Array<Extract<DecisionEntitlementResult, { entitled: false }>> = []
    for (const decisionId of entry.requiredDecisionIds) {
      const check = requireDecisionEntitled(decisionId, {
        enforceLegalSignOff: options.enforceLegalSignOff,
      })
      if (!check.entitled) {
        unmetDecisions.push(check)
      }
    }

    const overriddenStatus = options.statusOverrides?.[entry.id] ?? entry.status
    // A gate whose required decision is not entitled cannot report open / ok
    const effectiveStatus: GateStatus = unmetDecisions.length > 0 ? 'closed' : overriddenStatus

    const progressPatch = options.progressOverrides?.[entry.id]
    const currentProgress: GateProgress = progressPatch
      ? { ...entry.currentProgress, ...progressPatch }
      : entry.currentProgress

    let apiMeasureStatus: ApiMeasureStatus
    if (unmetDecisions.length > 0) {
      apiMeasureStatus = 'not_entitled'
      blockedByDecisionCount += 1
    } else if (effectiveStatus === 'open') {
      apiMeasureStatus = 'ok'
    } else if (entry.evaluationType !== 'deterministic' && currentProgress.have > 0) {
      apiMeasureStatus = 'insufficient_data'
    } else {
      apiMeasureStatus = 'not_collected'
    }

    byDomain[entry.domain].total += 1
    if (effectiveStatus === 'open') {
      openCount += 1
      byDomain[entry.domain].open += 1
    } else {
      closedCount += 1
      byDomain[entry.domain].closed += 1
    }

    return {
      gateId: entry.id,
      domain: entry.domain,
      step: entry.step,
      kind: entry.kind,
      capability: entry.capability,
      status: effectiveStatus,
      apiMeasureStatus,
      evaluationType: entry.evaluationType,
      requirement: entry.requirement,
      unlockCondition: entry.unlockCondition,
      currentProgress,
      requiredDecisionIds: entry.requiredDecisionIds,
      unmetDecisions,
    }
  })

  return {
    schemaVersion: '1.0',
    siteId: options.siteId ?? null,
    generatedAt: options.now ?? new Date().toISOString(),
    summary: {
      total: capabilities.length,
      open: openCount,
      closed: closedCount,
      blockedByDecision: blockedByDecisionCount,
      byDomain,
    },
    capabilities,
  }
}
