/**
 * Unified Gate Ledger (`gate_eval`, Master Architecture v2 §1.3 / §12.2 / §13 / consistency-sequence.md)
 *
 * Single source of truth across all eight domains (`tel`, `store`, `join`, `act`, `ml`, `ev`, `del`, `surf`).
 * Feeds `GET /v1/sites/{id}/capabilities` and every `gates.unmet[]` field in API / MCP envelopes.
 *
 * Statistical reading rule (§12.2):
 *   Every gate explicitly declares `evaluationType`:
 *     - `'fixed_horizon'`  : pre-registered sample size / date evaluated once (prevents daily peeking inflation)
 *     - `'always_valid'`   : continuous confidence sequence / run-in / rolling health window safe to inspect any time
 *     - `'deterministic'`  : structural proof, CI conformance suite, contract check, or recorded sign-off
 *
 * Note on namespace normalization:
 *   Working docs (`consistency-sequence.md`) abbreviate the Surface domain as `sur.*`.
 *   Per Batch 1 contract (`surf.*`), canonical ids use `surf.*` while `legacyAlias` preserves `sur.*`
 *   so lookups work seamlessly with both names.
 */

import {
  requireDecisionEntitled,
  type DecisionEntitlementResult,
  type DecisionId,
  type LedgerArea,
} from './decisions'

export type GateDomain = LedgerArea

export type GateStatus = 'open' | 'closed'

export type GateEvaluationType = 'fixed_horizon' | 'always_valid' | 'deterministic'

export type GateKind = 'exit' | 'run_in' | 'capability'

export type ApiMeasureStatus =
  | 'ok'
  | 'insufficient_data'
  | 'not_collected'
  | 'pending'
  | 'invalid'
  | 'not_applicable'
  | 'not_entitled'
  | 'suppressed'

export interface GateProgress {
  readonly have: number
  readonly need: number
  readonly unit: string
  readonly etaDays?: number | null
  readonly lastEvaluatedAt?: string | null
}

export interface GateEntry {
  readonly id: string
  readonly domain: GateDomain
  readonly step: string
  readonly kind: GateKind
  readonly capability: string
  readonly status: GateStatus
  readonly evaluationType: GateEvaluationType
  readonly requirement: string
  readonly unlockCondition: string
  readonly currentProgress: GateProgress
  readonly requiredDecisionIds: ReadonlyArray<DecisionId>
  readonly legacyAlias?: string
}

export interface CapabilityItem {
  readonly gateId: string
  readonly domain: GateDomain
  readonly step: string
  readonly kind: GateKind
  readonly capability: string
  readonly status: GateStatus
  readonly apiMeasureStatus: ApiMeasureStatus
  readonly evaluationType: GateEvaluationType
  readonly requirement: string
  readonly unlockCondition: string
  readonly currentProgress: GateProgress
  readonly requiredDecisionIds: ReadonlyArray<DecisionId>
  readonly unmetDecisions: ReadonlyArray<Extract<DecisionEntitlementResult, { entitled: false }>>
}

export interface CapabilitiesSummary {
  readonly schemaVersion: '1.0'
  readonly siteId: string | null
  readonly generatedAt: string
  readonly summary: {
    readonly total: number
    readonly open: number
    readonly closed: number
    readonly blockedByDecision: number
    readonly byDomain: Readonly<Record<GateDomain, { readonly total: number; readonly open: number; readonly closed: number }>>
  }
  readonly capabilities: ReadonlyArray<CapabilityItem>
}

export interface CapabilitiesSummaryOptions {
  readonly siteId?: string
  readonly domain?: GateDomain
  readonly statusOverrides?: Readonly<Record<string, GateStatus>>
  readonly progressOverrides?: Readonly<Record<string, Partial<GateProgress>>>
  readonly enforceLegalSignOff?: boolean
  readonly now?: string
}

type GateInput = {
  id: string
  domain: GateDomain
  step: string
  kind?: GateKind
  capability: string
  evaluationType: GateEvaluationType
  requirement: string
  unlockCondition: string
  need: number
  unit: string
  have?: number
  etaDays?: number | null
  decisions?: ReadonlyArray<DecisionId>
  status?: GateStatus
  legacyAlias?: string
}

function g(input: GateInput): GateEntry {
  return {
    id: input.id,
    domain: input.domain,
    step: input.step,
    kind: input.kind ?? 'exit',
    capability: input.capability,
    status: input.status ?? 'closed',
    evaluationType: input.evaluationType,
    requirement: input.requirement,
    unlockCondition: input.unlockCondition,
    currentProgress: {
      have: input.have ?? 0,
      need: input.need,
      unit: input.unit,
      etaDays: input.etaDays ?? null,
      lastEvaluatedAt: null,
    },
    requiredDecisionIds: input.decisions ?? [],
    ...(input.legacyAlias ? { legacyAlias: input.legacyAlias } : {}),
  }
}

function surfGate(input: Omit<GateInput, 'domain' | 'legacyAlias'>): GateEntry {
  const shortName = input.id.startsWith('surf.') ? input.id.slice('surf.'.length) : input.id
  return g({
    ...input,
    domain: 'surf',
    legacyAlias: `sur.${shortName}`,
  })
}

